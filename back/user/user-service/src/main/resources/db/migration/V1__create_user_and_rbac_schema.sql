-- 逻辑删除后允许重新注册同名账号；有效账号范围内仍由数据库兜底保证唯一性。
CREATE UNIQUE INDEX IF NOT EXISTS uk_t_user_username_active
    ON t_user (LOWER(username)) WHERE deleted = FALSE;
CREATE UNIQUE INDEX IF NOT EXISTS uk_t_user_phone_active
    ON t_user (phone) WHERE deleted = FALSE AND phone IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uk_t_user_email_active
    ON t_user (LOWER(email)) WHERE deleted = FALSE AND email IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_t_user_status_created_at
    ON t_user (status, created_at DESC) WHERE deleted = FALSE;

-- RBAC 角色表：built_in 标识由业务层保护的系统基础角色。
CREATE TABLE IF NOT EXISTS sys_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64)  NOT NULL,
    name        VARCHAR(64)  NOT NULL,
    description VARCHAR(255),
    status      SMALLINT     NOT NULL DEFAULT 1,
    built_in    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_sys_role_code UNIQUE (code)
);

-- 权限字典由迁移脚本维护，code 必须与控制器鉴权注解保持一致。
CREATE TABLE IF NOT EXISTS sys_permission (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(128) NOT NULL,
    name        VARCHAR(64)  NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_sys_permission_code UNIQUE (code)
);

-- 用户与角色、角色与权限均采用联合主键，天然阻止重复授权关系。
CREATE TABLE IF NOT EXISTS sys_user_role (
    user_id    BIGINT    NOT NULL REFERENCES t_user(id) ON DELETE CASCADE,
    role_id    BIGINT    NOT NULL REFERENCES sys_role(id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS sys_role_permission (
    role_id       BIGINT    NOT NULL REFERENCES sys_role(id) ON DELETE CASCADE,
    permission_id BIGINT    NOT NULL REFERENCES sys_permission(id) ON DELETE CASCADE,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, permission_id)
);

CREATE INDEX IF NOT EXISTS idx_sys_user_role_role_id ON sys_user_role (role_id);
CREATE INDEX IF NOT EXISTS idx_sys_role_permission_permission_id ON sys_role_permission (permission_id);

